"""Write the schema section of DESIGN.md from schema47.sql (roles, columns, PKs, FKs), so the two never drift.

usage: python3 schema_doc47.py            # rewrites the part of DESIGN.md between the SCHEMA markers
       python3 schema_doc47.py --print    # prints it instead
"""
import collections
import re
import sqlite3
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SQL = HERE / "schema47.sql"
DESIGN = HERE / "DESIGN.md"
BEGIN, END = "<!-- SCHEMA:BEGIN (generated by schema_doc47.py) -->", "<!-- SCHEMA:END -->"


def parse_sql(text):
    """-> list of (group, [(table, role, {column: comment})]) in file order, and views."""
    groups, cur, role = [], None, None
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        ln = lines[i]
        m = re.match(r"-- @group:\s*(.*)", ln)
        if m:
            cur = (m.group(1).strip(), [])
            groups.append(cur)
        m = re.match(r"-- @role:\s*(.*)", ln)
        if m:
            role = m.group(1).strip()
        m = re.match(r"CREATE (?:VIRTUAL )?TABLE (\w+)", ln)
        if m:
            name, notes = m.group(1), {}
            j = i + 1
            while j < len(lines) and not lines[j].startswith(");") and "CREATE" not in lines[j]:
                body = lines[j]
                if "--" in body:
                    code, note = body.split("--", 1)
                    cols = re.findall(r"(?:^|,)\s*(\w+)\s+(?:TEXT|INTEGER|REAL)", code)
                    if cols:
                        notes[cols[-1]] = note.strip()
                j += 1
            if cur is not None:
                cur[1].append((name, role, notes))
            role = None
        i += 1
    return groups


def render():
    text = SQL.read_text()
    db = sqlite3.connect(":memory:")
    db.executescript(text)
    out = []
    n_tab = 0
    for group, tables in parse_sql(text):
        out.append(f"### {group}\n")
        for name, role, notes in tables:
            n_tab += 1
            info = db.execute(f"PRAGMA table_info({name})").fetchall()
            pk = [r[1] for r in sorted(info, key=lambda r: r[5]) if r[5]]
            fks = collections.defaultdict(list)
            for fk in db.execute(f"PRAGMA foreign_key_list({name})"):
                fks[fk[0]].append(fk)
            fk_txt = []
            for rows in fks.values():
                src = ", ".join(r[3] for r in rows)
                dst = ", ".join(r[4] or "pk" for r in rows)
                fk_txt.append(f"{src} → {rows[0][2]}({dst})")
            uniq = []
            for ix in db.execute(f"PRAGMA index_list({name})"):
                if ix[2] and ix[3] == "u":
                    cols = [r[2] for r in db.execute(f"PRAGMA index_info('{ix[1]}')")]
                    uniq.append("(" + ", ".join(cols) + ")" + (" partial" if ix[4] else ""))
            out.append(f"**`{name}`** — {role or ''}  ")
            if pk:
                out.append(f"PK ({', '.join(pk)})" + (f"; unique {'; '.join(uniq)}" if uniq else "") + "  ")
            if fk_txt:
                out.append("FK " + "; ".join(fk_txt) + "  ")
            cols = []
            for r in info:
                c = f"`{r[1]}`"
                if r[1] in notes:
                    c += f" ({notes[r[1]]})"
                cols.append(c)
            if name == "search_fts":
                cols = ["`folded`, `stemmed` (FTS5 over search_units, rowid = uid)"]
            out.append("Columns: " + ", ".join(cols) + "\n")
    views = [r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='view' ORDER BY rowid")]
    out.append("### Derived views (computed, never stored; materialised per release at scale)\n")
    for v in views:
        m = re.search(r"((?:--[^\n]*\n)+)CREATE VIEW " + v + r"\b", text)
        why = " ".join(l.lstrip("- ").strip() for l in m.group(1).splitlines()) if m else ""
        out.append(f"- **`{v}`** — {why}")
    header = f"{n_tab} tables (incl. the FTS index) and {len(views)} views; full definitions in `schema47.sql`.\n"
    return header + "\n" + "\n".join(out) + "\n"


def main():
    sec = render()
    if "--print" in sys.argv:
        print(sec)
        return
    doc = DESIGN.read_text()
    a, b = doc.index(BEGIN) + len(BEGIN), doc.index(END)
    DESIGN.write_text(doc[:a] + "\n" + sec + doc[b:])


if __name__ == "__main__":
    main()
