"""The e-reader edition: one EPUB 3 per article, from the same renderer as the reading HTML (experiment 35).

    write_epub(ed, out_root) -> stats         <out_root>/<id>/<id>.epub

Reflowable, right to left (spine page-progression-direction="rtl", html dir="rtl"), the reading fonts embedded
(OFL, subset WOFF), notes as EPUB 3 footnotes (noteref -> aside epub:type="footnote"), formulas as MathML (the
content document is declared properties="mathml"), tables as XHTML tables. No scan images: the EPUB is the text;
the scan lives with the reading HTML. Dublin Core: title, creators, language, identifier, date, publisher, source
(the Mandumah record and the master files), and the modification time EPUB 3 requires.
"""
from __future__ import annotations

import datetime as dt
import zipfile
from html import escape
from pathlib import Path

from lxml import etree

from .html import CSS, Renderer, bundle_fonts, font_css

XHTML = "http://www.w3.org/1999/xhtml"

EPUB_CSS = CSS + """
button.og{display:none}
"""


def a(s) -> str:
    return escape(str(s or ""), quote=True)


def _xhtml(title: str, body: str, css: str = "style.css") -> str:
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE html>\n'
            f'<html xmlns="{XHTML}" xmlns:epub="http://www.idpf.org/2007/ops" lang="ar" xml:lang="ar" dir="rtl">'
            f'<head><meta charset="utf-8"/><title>{a(title)}</title>'
            f'<link rel="stylesheet" type="text/css" href="{css}"/></head><body>{body}</body></html>\n')


def write_epub(ed, out_root) -> dict:
    out_root = Path(out_root)
    d = out_root / ed.stem
    d.mkdir(parents=True, exist_ok=True)
    fonts = bundle_fonts(out_root / "fonts")
    f = ed.front
    title = f.get("title") or ed.stem
    r = Renderer(ed, "epub")
    art = r.article(links=[])
    text = _xhtml(title, art)
    etree.fromstring(text.encode())                       # well-formed, or fail here rather than in a reader
    has_math = "<math" in art

    # navigation: the title, then the body's headings (top two levels), notes, references
    items = [f'<li><a href="text.xhtml">{a(title)}</a></li>']
    for n in ed.body:
        if n.kind == "heading" and n.level <= 2 and n.id and n.text.strip():
            items.append(f'<li><a href="text.xhtml#j-{a(n.id)}">{a(n.text[:120])}</a></li>')
    if ed.refs:
        items.append('<li><a href="text.xhtml#refs">المراجع</a></li>')
    if ed.notes:
        items.append('<li><a href="text.xhtml#notes">الهوامش</a></li>')
    nav = _xhtml("المحتويات", f'<nav epub:type="toc" id="toc"><h1>المحتويات</h1><ol>{"".join(items)}</ol></nav>')
    # the heading ids exist only if the renderer kept them unchanged (uid adds a suffix to a repeated id)
    nav_doc = etree.fromstring(nav.encode())
    text_ids = set(etree.fromstring(text.encode()).xpath("//@id"))
    for li in nav_doc.iter(f"{{{XHTML}}}a"):
        h = li.get("href", "")
        if "#" in h and h.split("#", 1)[1] not in text_ids:
            li.set("href", "text.xhtml")
    nav = '<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE html>\n' + etree.tostring(nav_doc, encoding="unicode")

    ident = f"urn:mandumah:{f.get('article_id') or ed.stem}"
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    md = [f'<dc:identifier id="uid">{a(ident)}</dc:identifier>', f"<dc:title>{a(title)}</dc:title>",
          "<dc:language>ar</dc:language>", f'<meta property="dcterms:modified">{now}</meta>']
    for i, au in enumerate(f.get("authors", []), 1):
        nm = au.get("name_ar") or au.get("display") or au.get("name_en")
        if nm:
            md.append(f'<dc:creator id="cr{i}">{a(nm)}</dc:creator>')
            md.append(f'<meta refines="#cr{i}" property="role" scheme="marc:relators">aut</meta>')
    if f.get("year"):
        md.append(f"<dc:date>{a(f['year'])}</dc:date>")
    if f.get("publisher") or f.get("journal"):
        md.append(f"<dc:publisher>{a(f.get('publisher') or f.get('journal'))}</dc:publisher>")
    src = [f"{f.get('journal', '')} {f.get('volume', '')}/{f.get('issue', '')}".strip(" /")]
    if f.get("record"):
        src.append(f"Mandumah record {f['record']}")
    src.append(f"master files {ed.stem}.jats.xml + {ed.stem}.alto.xml")
    md.append(f"<dc:source>{a('; '.join(x for x in src if x))}</dc:source>")
    for kg in f.get("keywords", []):
        for k in kg.get("kwds", []):
            md.append(f"<dc:subject>{a(k)}</dc:subject>")
    ab = next((x for x in f.get("abstracts", []) if x.get("lang", "ar") == "ar"), None)
    if ab:
        md.append(f"<dc:description>{a(' '.join(ab.get('paras', [])))}</dc:description>")
    md.append("<dc:rights>Generated by inkscript (experiment 35) from the master files; text as read from the "
              "printed page. Fonts: SIL Open Font Licence.</dc:rights>")

    props = ' properties="mathml"' if has_math else ""
    man = ['<item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>',
           f'<item id="text" href="text.xhtml" media-type="application/xhtml+xml"{props}/>',
           '<item id="css" href="style.css" media-type="text/css"/>']
    for i, fo in enumerate(fonts):
        man.append(f'<item id="font{i}" href="fonts/{fo["file"]}" media-type="font/woff"/>')
    opf = ('<?xml version="1.0" encoding="UTF-8"?>\n'
           '<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="uid" xml:lang="ar" '
           'dir="rtl"><metadata xmlns:dc="http://purl.org/dc/elements/1.1/">' + "".join(md) + "</metadata>"
           "<manifest>" + "".join(man) + '</manifest><spine page-progression-direction="rtl">'
           '<itemref idref="text"/></spine></package>\n')
    container = ('<?xml version="1.0" encoding="UTF-8"?>\n<container version="1.0" '
                 'xmlns="urn:oasis:names:tc:opendocument:xmlns:container"><rootfiles>'
                 '<rootfile full-path="OEBPS/package.opf" media-type="application/oebps-package+xml"/>'
                 "</rootfiles></container>\n")
    css = font_css(fonts, "fonts/") + EPUB_CSS
    p = d / f"{ed.stem}.epub"
    tmp = p.with_suffix(".part")
    with zipfile.ZipFile(tmp, "w") as z:
        z.writestr(zipfile.ZipInfo("mimetype"), "application/epub+zip", compress_type=zipfile.ZIP_STORED)
        z.writestr("META-INF/container.xml", container, compress_type=zipfile.ZIP_DEFLATED)
        z.writestr("OEBPS/package.opf", opf, compress_type=zipfile.ZIP_DEFLATED)
        z.writestr("OEBPS/nav.xhtml", nav, compress_type=zipfile.ZIP_DEFLATED)
        z.writestr("OEBPS/text.xhtml", text, compress_type=zipfile.ZIP_DEFLATED)
        z.writestr("OEBPS/style.css", css, compress_type=zipfile.ZIP_DEFLATED)
        for fo in fonts:
            z.write(out_root / "fonts" / fo["file"], f"OEBPS/fonts/{fo['file']}", compress_type=zipfile.ZIP_STORED)
    tmp.replace(p)
    return dict(epub=str(p), epub_bytes=p.stat().st_size, mathml=has_math)
